export function toEvent(row: Row, stage?: Stage, options: Partial<Event> = {}): Event {
  const [id,title,category,art,description,...decisions] = row
  const choices: Choice[] = decisions.filter((item): item is Decision => Boolean(item)).map(([label,result,code,when], index) =>
    ({ id: String(index),label,result,effects:effects(code),when }))
  return { id,title,category,art,description,choices,stages:stage ? [stage] : undefined,
    importance: category === '특수' ? 4 : 2, record: true, weight: category === '특수' ? .65 : 1, ...options }
}
