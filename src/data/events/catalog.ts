function effects(source: string): Changes {
  const result: Changes = {}
  for (const term of source.split(' ')) {
    const [id,number,trust] = term.split(':')
    const value = Number(number)
    if (id in stats) (result.stats ??= {})[stats[id]] = value
    else if (id in vitals) (result.vitals ??= {})[vitals[id]] = value
    else if (id in skills) (result.skills ??= {})[skills[id]] = value
    else if (id.startsWith('@')) result.relationship = [...[result.relationship ?? []].flat(), { id:id.slice(1), affinity:value, trust:Number(trust) }]
    else if (id.startsWith('#')) result.flag = id.slice(1)
    else if (id.startsWith('+')) result.trait = id.slice(1)
    else if (id.startsWith('>')) result.follows = id.slice(1)
  }
  return result
}

